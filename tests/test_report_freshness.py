def test_a_trailer_may_record_its_invocation(repo: Path) -> None:
    assert split_invocation("scripts/x.py --skip-txgnn") == ("scripts/x.py",
                                                             ["--skip-txgnn"])
    (repo / "reports" / "pipeline" / "d_v1.md").write_text(
        "# D\n\nGenerated by `scripts/gen.py --fast`.\n", encoding="utf-8")
    _commit(repo, "add d", "2026-01-02T00:00:00")
    assert generator_for(repo, "reports/pipeline/d_v1.md") == "scripts/gen.py"
    assert generator_args(repo, "reports/pipeline/d_v1.md") == ["--fast"]
    assert scan(repo)[1] == []


