# -- the environment the gate refuses to run in ------------------------------

def test_a_shallow_clone_is_refused_not_silently_passed(repo: Path,
                                                        tmp_path: Path) -> None:
    """At depth 1 every path resolves to the same commit, so nothing looks
    stale. Passing there would be the gate's own failure mode."""
    _touch_code(repo, "scripts/gen.py", "2026-02-01T00:00:00")
    assert scan(repo)[0], "sanity: deep clone sees the staleness"

    shallow = tmp_path / "shallow"
    subprocess.run(["git", "clone", "-q", "--depth", "1",
                    repo.as_uri(), str(shallow)], check=True, capture_output=True)
    assert (shallow / ".git" / "shallow").exists()
    with pytest.raises(ShallowRepository, match="fetch-depth"):
        scan(shallow)


def test_a_full_clone_passes_the_depth_check(repo: Path) -> None:
    assert_deep(repo)


# -- the import closure ------------------------------------------------------
#
# Every case here is a shape that was marked FRESH while stale in the real
# repository, because a "Generated by" trailer is a hand-written declaration and
# the code that moved was one import further in.

TRAILER_SCRIPT_ONLY = "Generated by `scripts/gen.py`."


def _script_only_report(repo: Path, body: str) -> None:
    (repo / "reports" / "pipeline" / "s_v1.md").write_text(
        f"# S\n\nrho = +0.5\n\n{TRAILER_SCRIPT_ONLY}\n", encoding="utf-8")
    (repo / "scripts" / "gen.py").write_text(body, encoding="utf-8")


def test_a_module_the_script_imports_counts_even_when_undeclared(repo: Path) -> None:
    """manuscript_robustness.md: trailer named only the script; the ablation was
    computed by a module it imports, which had since gained a leakage fix."""
    _script_only_report(repo, "from mammal_repurposing.cluster_a import mod\n")
    _commit(repo, "script-only trailer", "2026-01-02T00:00:00")
    # Scoped to this report: rewriting gen.py in a later commit legitimately
    # makes the fixture's OTHER report stale, which is the gate working.
    assert [s for s in scan(repo)[0] if s.report == "reports/pipeline/s_v1.md"] == []

    _touch_code(repo, "src/mammal_repurposing/cluster_a/mod.py",
                "2026-02-01T00:00:00")
    stale = [s for s in scan(repo)[0] if s.report == "reports/pipeline/s_v1.md"]
    assert [s.code for s in stale] == ["src/mammal_repurposing/cluster_a/mod.py"]


def test_the_closure_is_transitive(repo: Path) -> None:
    """disease_reframe.py declared, but it does `from . import retrospective`
    and calls into it. The gate has to follow the second hop."""
    deep = repo / "src" / "mammal_repurposing" / "cluster_a" / "deep.py"
    deep.write_text("Z = 1\n", encoding="utf-8")
    (repo / "src" / "mammal_repurposing" / "cluster_a" / "mod.py").write_text(
        "from mammal_repurposing.cluster_a import deep\ny = 1\n", encoding="utf-8")
    _script_only_report(repo, "from mammal_repurposing.cluster_a import mod\n")
    _commit(repo, "two hops", "2026-01-02T00:00:00")

    _touch_code(repo, "src/mammal_repurposing/cluster_a/deep.py",
                "2026-02-01T00:00:00")
    stale = [s for s in scan(repo)[0] if s.report == "reports/pipeline/s_v1.md"]
    assert [s.code for s in stale] == ["src/mammal_repurposing/cluster_a/deep.py"]


def test_relative_imports_resolve(repo: Path) -> None:
    """`from . import retrospective as R` is the exact spelling that hid the
    AUROC the website was publishing."""
    sib = repo / "src" / "mammal_repurposing" / "cluster_a" / "sib.py"
    sib.write_text("W = 1\n", encoding="utf-8")
    (repo / "src" / "mammal_repurposing" / "cluster_a" / "mod.py").write_text(
        "from . import sib as S\ny = 1\n", encoding="utf-8")
    _script_only_report(repo, "from mammal_repurposing.cluster_a import mod\n")
    _commit(repo, "relative import", "2026-01-02T00:00:00")

    _touch_code(repo, "src/mammal_repurposing/cluster_a/sib.py",
                "2026-02-01T00:00:00")
    stale = [s for s in scan(repo)[0] if s.report == "reports/pipeline/s_v1.md"]
    assert [s.code for s in stale] == ["src/mammal_repurposing/cluster_a/sib.py"]


def test_imports_inside_a_function_count(repo: Path) -> None:
    """The scripts here import their modules inside main(), which is where both
    real misses were hiding. A module-level-only walk would not have seen them."""
    _script_only_report(
        repo,
        "def main():\n"
        "    from mammal_repurposing.cluster_a import mod\n"
        "    return mod\n")
    _commit(repo, "function-local import", "2026-01-02T00:00:00")

    _touch_code(repo, "src/mammal_repurposing/cluster_a/mod.py",
                "2026-02-01T00:00:00")
    stale = [s for s in scan(repo)[0] if s.report == "reports/pipeline/s_v1.md"]
    assert [s.code for s in stale] == ["src/mammal_repurposing/cluster_a/mod.py"]


def test_third_party_imports_are_not_followed(repo: Path) -> None:
    _script_only_report(repo, "import numpy as np\nimport pandas\n")
    _commit(repo, "third party", "2026-01-02T00:00:00")
    assert import_closure(repo, "scripts/gen.py") == {"scripts/gen.py"}


def test_a_syntax_error_does_not_break_the_gate(repo: Path) -> None:
    """A broken file is the test suite's problem. This gate degrades to the
    declared set rather than raising and taking CI down with it."""
    _script_only_report(repo, "def main(:\n    pass\n")
    _commit(repo, "unparseable", "2026-01-02T00:00:00")
    assert import_closure(repo, "scripts/gen.py") == {"scripts/gen.py"}


def test_an_import_cycle_terminates(repo: Path) -> None:
    a = repo / "src" / "mammal_repurposing" / "cluster_a" / "mod.py"
    b = repo / "src" / "mammal_repurposing" / "cluster_a" / "other.py"
    a.write_text("from . import other\n", encoding="utf-8")
    b.write_text("from . import mod\n", encoding="utf-8")
    _script_only_report(repo, "from mammal_repurposing.cluster_a import mod\n")
    _commit(repo, "cycle", "2026-01-02T00:00:00")
    got = import_closure(repo, "scripts/gen.py")
    assert "src/mammal_repurposing/cluster_a/other.py" in got
    assert "src/mammal_repurposing/cluster_a/mod.py" in got
